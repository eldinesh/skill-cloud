// The Koru kit's classes and the component each one is. A kit class counts only when that
// component is in the project's manifest (under its own name or a common alias).
const KIT_CLASSES = { 'k-btn': 'Button', 'k-input': 'TextField', 'k-select': 'Select', 'k-check': 'Checkbox', 'k-card': 'Card', 'k-table': 'Table', 'k-badge': 'Badge', 'k-alert': 'Alert', 'k-toast': 'Toast', 'k-dialog': 'Dialog', 'k-tabs': 'Tabs', 'k-tab': 'Tabs', 'k-avatar': 'Avatar', 'k-timeline': 'Timeline', 'k-skeleton': 'Skeleton', 'k-empty': 'EmptyState', 'k-ai': 'AISuggestion', 'k-confidence': 'Confidence', 'k-explain': 'Explanation', 'k-undo': 'UndoBar' };
const ALIASES = [['textfield', 'textinput', 'input', 'text input'], ['dialog', 'modal'], ['table', 'datatable', 'data table'], ['badge', 'statusbadge', 'status badge', 'tag', 'pill'], ['toast', 'notification'], ['undobar', 'undo'], ['aisuggestion', 'ai suggestion', 'suggestion'], ['emptystate', 'empty']];
function sameComponent(a, b) {
  const n = (x) => String(x).toLowerCase().replace(/\s*\(.*\)$/, '');
  if (n(a) === n(b)) return true;
  return ALIASES.some((g) => g.includes(n(a)) && g.includes(n(b)));
}

const TW_PALETTE = new Set('slate gray zinc neutral stone red orange amber yellow lime green emerald teal cyan sky blue indigo violet purple fuchsia pink rose'.split(' '));
const CONTROL_TAGS = /<(button|input|select|textarea|dialog)\b([^>]*)>/gi;
const LINT_EXT = /\.(html?|css|jsx|tsx|js|ts|vue|svelte)$/i;

function lineOf(text, idx) { return text.slice(0, idx).split('\n').length; }

function cssContexts(text, ext) {
  // Returns [{start, body}] regions where CSS values live.
  const out = [];
  if (/^\.css$/i.test(ext)) return [{ start: 0, body: text }];
  for (const m of text.matchAll(/<style\b([^>]*)>([\s\S]*?)<\/style>/gi)) {
    if (/data-koru-tokens/.test(m[1])) continue;
    out.push({ start: m.index + m[0].indexOf(m[2]), body: m[2] });
  }
  for (const m of text.matchAll(/\sstyle\s*=\s*"([^"]*)"/gi)) out.push({ start: m.index, body: m[1] });
  for (const m of text.matchAll(/style=\{\{([\s\S]*?)\}\}/g)) out.push({ start: m.index, body: m[1] });
  return out;
}

function lintText(root, file, text) {
  const ds = load(root);
  const findings = [];
  const add = (idx, rule, msg, level = 'block') => findings.push({ line: lineOf(text, idx), rule, msg, level });
  const ext = path.extname(file);
  const rel = path.relative(root, path.resolve(file)).split(path.sep).join('/');
  if (/(^|\/)koru\/design-system\//.test(rel) || /tokens\.(css|json)$/.test(rel)) return findings;
  if (!ds.ready) { findings.push({ line: 1, rule: 'no-system', msg: 'No design system is set up for this project. Run the koru-design-system skill first (koru ds adopt koru-neutral for behaviour-first prototypes).', level: 'block' }); return findings; }
  const man = ds.manifest;
  const names = new Set(man.components.map((c) => c.name.toLowerCase()));
  const inManifest = (n) => man.components.some((c) => sameComponent(c.name, n));
  const match = man.match || {};
  const inUiLayer = man.uiLayer && rel.includes(String(man.uiLayer).replace(/^\.?\//, ''));
  const toks = flatten(ds.tokens || {});
  const spaceVals = new Set(toks.filter((t) => t.path.startsWith('space.')).map((t) => String(t.value)));
  const sizeVals = new Set(toks.filter((t) => t.path.startsWith('font.size.')).map((t) => String(t.value)));
  const colourGroups = new Set(toks.filter((t) => t.path.startsWith('color.')).map((t) => t.path.split('.')[1]));
  const spaceKeys = new Set(toks.filter((t) => t.path.startsWith('space.')).map((t) => t.path.split('.')[1]));

  // 1. The inlined token block must be exactly the build output.
  const blk = text.match(/<style data-koru-tokens>([\s\S]*?)<\/style>/);
  if (blk && blk[1].trim() !== inlineBlock(root)) add(blk.index, 'token-block', 'The inlined design-system block differs from the build. Never edit it by hand: change tokens.json, run koru ds build, then koru ds inline <file>.');
  // The rest of the lint reads the page without the block (it is the system itself), keeping line numbers.
  text = text.replace(/(<style data-koru-tokens>)([\s\S]*?)(<\/style>)/, (m0, a, b, c) => a + b.replace(/[^\n]/g, '') + c);

  // 2. Literal colours and off-scale values in CSS.
  for (const ctx of cssContexts(text, ext)) {
    for (const m of ctx.body.matchAll(/#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|oklch|lab|lch)\(/g)) {
      if (/^#[0-9a-fA-F]+$/.test(m[0]) && ![3, 4, 6, 8].includes(m[0].length - 1)) continue;
      add(ctx.start + m.index, 'raw-colour', `Literal colour ${m[0]}. Use a colour token (var(--color-…)${man.tailwind ? ' or its Tailwind class' : ''}).`);
    }
    for (const m of ctx.body.matchAll(/\b(margin|padding|gap|row-gap|column-gap)(?:-[a-z]+)?\s*:\s*([^;}"]+)/gi)) {
      for (const v of m[2].match(/-?\d*\.?\d+px/g) || []) if (v !== '0px' && !spaceVals.has(v.replace('-', ''))) add(ctx.start + m.index, 'off-scale', `${m[1]} ${v} is not on the spacing scale (${[...spaceVals].join(', ')}). Use var(--space-…).`);
    }
    for (const m of ctx.body.matchAll(/\bfont-size\s*:\s*([^;}"]+)/gi)) if (!/var\(/.test(m[1]) && !sizeVals.has(m[1].trim())) add(ctx.start + m.index, 'off-scale', `font-size ${m[1].trim()} is not a type token. Use var(--font-size-…).`);
    for (const m of ctx.body.matchAll(/\bfont-family\s*:\s*([^;}"]+)/gi)) if (!/var\(|inherit/.test(m[1])) add(ctx.start + m.index, 'raw-font', 'Literal font-family. Use var(--font-family-…).');
  }
  // Literal colours as plain strings in scripts (style objects, chart colours).
  if (/\.(jsx|tsx|js|ts|vue|svelte|html?)$/i.test(ext)) for (const m of text.matchAll(/["'`](#[0-9a-fA-F]{6}|#[0-9a-fA-F]{3}|rgba?\([^)]*\))["'`]/g)) add(m.index, 'raw-colour', `Literal colour ${m[1]} in script. Read it from the tokens (getComputedStyle or the tokens module).`);

  // 3. Tailwind: arbitrary values, Tailwind's own palette, off-scale spacing.
  for (const m of text.matchAll(/(?:class|className)\s*=\s*(?:"([^"]*)"|'([^']*)'|\{`([^`]*)`\})/g)) {
    const cls = (m[1] || m[2] || m[3] || '').split(/\s+/);
    for (const c of cls) {
      const base = c.split(':').pop();
      if (/-\[[^\]]+\]/.test(base)) add(m.index, 'arbitrary-value', `Arbitrary value "${c}". Use a token class.`);
      const pal = base.match(/^(?:bg|text|border|ring|outline|fill|stroke|from|via|to|divide|placeholder|accent|caret|decoration|shadow)-([a-z]+)-(\d{2,3})(?:\/\d+)?$/);
      if (pal && TW_PALETTE.has(pal[1]) && !colourGroups.has(pal[1])) add(m.index, 'off-palette', `"${c}" uses Tailwind's ${pal[1]} palette, which is not a token. Use ${[...colourGroups].slice(0, 6).join(', ')}.`);
      if (man.tailwind && spaceKeys.size) {
        const sp = base.match(/^-?(p|px|py|pt|pr|pb|pl|ps|pe|m|mx|my|mt|mr|mb|ml|gap|gap-x|gap-y|space-x|space-y)-(\d+(?:\.\d+)?)$/);
        if (sp && !spaceKeys.has(sp[2])) add(m.index, 'off-scale', `"${c}" is not on the spacing scale (${[...spaceKeys].join(', ')}).`);
      }
    }
  }

  // 3b. Text on background inside one class list must meet AA (large text 3:1).
  if (ds.tokens) for (const m of text.matchAll(/(?:class|className)\s*=\s*"([^"]*)"/g)) {
    const cls = m[1].split(/\s+/).map((c) => c.split(':').pop());
    const bg = cls.map((c) => c.match(/^bg-([a-z]+(?:-[a-z]+)?(?:-\d{2,3})?)$/)).find(Boolean);
    const fg = cls.map((c) => c.match(/^text-([a-z]+(?:-[a-z]+)?(?:-\d{2,3})?)$/)).find((x) => x && !/^(xs|sm|base|md|lg|xl|\dxl|left|right|center|start|end)$/.test(x[1]));
    if (!bg || !fg) continue;
    const val = (n) => (n === 'white' ? '#FFFFFF' : n === 'black' ? '#000000' : resolve(ds.tokens, `color.${n.replace(/-(\d{2,3})$/, '.$1')}`));
    const r = ratio(val(fg[1]), val(bg[1]));
    if (r === null) continue;
    const large = cls.some((c) => /^text-(lg|xl|\dxl)$/.test(c));
    if (r < (large ? 3 : 4.5)) add(m.index, 'contrast', `${fg[0]} on ${bg[0]} is ${Math.round(r * 100) / 100}:1; AA needs ${large ? '3' : '4.5'}:1. Use a darker shade token.`);
  }

  // 4. Components: only the manifest's.
  const known = (attrs) => {
    const ds = attrs.match(/data-ds\s*=\s*"([^"]+)"/);
    if (ds) return inManifest(ds[1]) ? true : `data-ds="${ds[1]}" is not in the manifest`;
    const cls = (attrs.match(/class(?:Name)?\s*=\s*"([^"]*)"/) || [])[1] || '';
    const kit = cls.split(/\s+/).map((c) => KIT_CLASSES[c]).find(Boolean);
    if (kit) return inManifest(kit) ? true : `${kit} (class ${Object.keys(KIT_CLASSES).find((k) => KIT_CLASSES[k] === kit)}) is not in ${man.system}`;
    if ((match.classPrefixes || []).some((p) => cls.split(/\s+/).some((c) => c.startsWith(p)))) return true;
    if (match.dataSlot && /data-slot=/.test(attrs)) return true;
    return false;
  };
  if (/\.(html?|jsx|tsx|vue|svelte)$/i.test(ext) && !inUiLayer) {
    for (const m of text.matchAll(CONTROL_TAGS)) {
      if (/type\s*=\s*"hidden"/.test(m[2])) continue;
      const k = known(m[2]);
      if (k === true) continue;
      add(m.index, k ? 'unknown-component' : 'bare-control', k ? `${k}. Add it through the design-system skill (koru ds component add …) with a spec, or use an existing one.` : `A bare <${m[1]}>. Use the system's component and mark it data-ds="…" (${[...names].slice(0, 8).join(', ')}…).`);
    }
    for (const m of text.matchAll(/(?:class|className)\s*=\s*"([^"]*)"/g)) {
      const kits = [...new Set(m[1].split(/\s+/).map((c) => KIT_CLASSES[c]).filter(Boolean))];
      for (const k of kits) if (!inManifest(k)) add(m.index, 'unknown-component', `${k} is not in ${man.system}. If the work needs it, add it with koru ds component add ${k} --spec SCR-…, so it is recorded as a gap to contribute back.`);
    }
    // A standalone prototype must carry the system: the inlined token block, the built CSS, or the system's own stylesheet.
    if (/\.html?$/i.test(ext) && /<html/i.test(text)) {
      const sysCss = ((man.prototype || {}).css || []).concat((man.prototype || {}).js || [], (man.prototype || {}).js_module || []);
      if (!/<style data-koru-tokens>/.test(text) && !/tokens\.css/.test(text) && !sysCss.some((u) => text.includes(u))) add(0, 'no-tokens', `This page does not load ${man.system}. Run koru ds inline ${rel} to add the token block and kit.`);
    }
    for (const m of text.matchAll(/data-ds\s*=\s*"([^"]+)"/g)) if (!inManifest(m[1])) add(m.index, 'unknown-component', `data-ds="${m[1]}" is not in the manifest. Add it with koru ds component add, or use an existing component.`);
    const tagPrefixes = match.tagPrefixes || [];
    for (const m of text.matchAll(/<([a-z][a-z0-9]*-[a-z0-9-]+)\b/g)) {
      const tag = m[1];
      if (!tagPrefixes.some((p) => tag.startsWith(p))) { add(m.index, 'unknown-component', `<${tag}> is not part of ${man.system}.`); continue; }
      if (man.components.length && !inManifest(tag) && man.components.some((c) => c.name.startsWith(tagPrefixes[0]))) add(m.index, 'unknown-component', `<${tag}> is not in the manifest.`);
    }
    // Imports from other UI libraries.
    const allowed = ((man.frontend || {}).imports || []);
    const uiLibs = /^(@mui|@material|@carbon|@fluentui|@primer|antd|@adobe|@react-spectrum|@chakra-ui|@mantine|react-bootstrap|bootstrap|@headlessui|@radix-ui)/;
    for (const m of text.matchAll(/import\s+[^'"]*from\s+['"]([^'"]+)['"]/g)) if (uiLibs.test(m[1]) && !allowed.some((a) => m[1].startsWith(a))) add(m.index, 'foreign-library', `Imports ${m[1]}, which is not ${man.system}.`);
  }

  // 5. Accessibility basics a lint can see.
  if (/\.(html?|jsx|tsx|vue|svelte)$/i.test(ext)) {
    for (const m of text.matchAll(/<img\b(?![^>]*\balt\s*=)[^>]*>/gi)) add(m.index, 'a11y-alt', '<img> without alt text (use alt="" for decoration).');
    for (const m of text.matchAll(/<(div|span|td|li)\b(?=[^>]*\bon[cC]lick)(?![^>]*\brole\s*=)[^>]*>/g)) add(m.index, 'a11y-click', `A clickable <${m[1]}> with no role. Use a Button component.`);
    for (const m of text.matchAll(/\b(?:window\.)?(confirm|alert|prompt)\s*\(/g)) add(m.index, 'native-dialog', `Native ${m[1]}(). Use the system's Dialog.`);
    for (const m of text.matchAll(/outline\s*:\s*(none|0)\b/g)) add(m.index, 'a11y-focus', 'Focus outline removed. Keep a visible focus style (the kit sets one).', 'warn');
  }
  return findings;
}

function lintFile(root, file) { return lintText(root, file, fs.readFileSync(file, 'utf8')); }

function lintTargets(root, files) {
  const out = [];
  const walk = (d) => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); const st = fs.statSync(p); if (st.isDirectory()) { if (!/node_modules|\.git|dist|build/.test(f)) walk(p); } else if (LINT_EXT.test(f)) out.push(p); } };
  if (files && files.length) { for (const f of files) { const p = path.resolve(f); if (fs.existsSync(p) && fs.statSync(p).isDirectory()) walk(p); else out.push(p); } return out; }
  const d = K.paths(root).deliverables;
  if (fs.existsSync(d)) walk(d);
  const fe = K.readEngagement(root).frontend_dir;
  if (fe && fs.existsSync(path.resolve(root, fe))) walk(path.resolve(root, fe));
  return out;
}

// Paths the hook guards: deliverables and the front-end folder named in engagement.md.
function isGuardedPath(root, file) {
  if (!LINT_EXT.test(file)) return false;
  const rel = path.relative(root, path.resolve(file)).split(path.sep).join('/');
  if (rel.startsWith('..')) return false;
  if (rel.startsWith('koru/deliverables/')) return true;
  const fe = String(K.readEngagement(root).frontend_dir || '').replace(/^\.?\//, '').replace(/\/$/, '');
  return !!fe && (rel === fe || rel.startsWith(fe + '/')) && !/node_modules\//.test(rel);
}

