'use strict';
// Koru design systems: one profile per project, tokens as the only source of values, a component
// manifest as the only source of components, and a lint that refuses anything else.
//
//   koru/design-system.md                 profile: system, source, version, licence, stack (people edit)
//   koru/design-system/tokens.json        tokens in W3C DTCG format (the only place literals live)
//   koru/design-system/components.json    the components a deliverable may use, with status and spec
//   koru/design-system/build/             generated: tokens.css, tailwind.preset.js, components.css, gallery.html

const fs = require('fs');
const path = require('path');
const K = require('./core');

const CATALOG = JSON.parse(fs.readFileSync(path.join(__dirname, 'ds-catalog.json'), 'utf8'));
const SEED_DIR = path.join(__dirname, 'ds');

function dsPaths(root) {
  const d = path.join(K.paths(root).koru, 'design-system');
  return {
    profile: K.paths(root).ds, dir: d,
    tokens: path.join(d, 'tokens.json'), manifest: path.join(d, 'components.json'),
    build: path.join(d, 'build'),
    css: path.join(d, 'build', 'tokens.css'), preset: path.join(d, 'build', 'tailwind.preset.js'),
    kit: path.join(d, 'build', 'components.css'), gallery: path.join(d, 'build', 'gallery.html'),
  };
}

const readJson = (f, dflt) => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { return dflt; } };
const writeFile = (f, s) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s); };

function load(root) {
  const p = dsPaths(root);
  const profile = fs.existsSync(p.profile) ? K.splitCard(fs.readFileSync(p.profile, 'utf8')).meta : {};
  const tokens = readJson(p.tokens, null);
  const manifest = readJson(p.manifest, null);
  return { paths: p, profile, tokens, manifest, ready: !!(manifest && manifest.components) };
}

// ---------------------------------------------------------------- tokens

function flatten(tokens) {
  const out = [];
  const walk = (node, trail, inheritedType) => {
    if (!node || typeof node !== 'object') return;
    const type = node.$type || inheritedType;
    if (Object.prototype.hasOwnProperty.call(node, '$value')) {
      out.push({ path: trail.join('.'), type, value: node.$value, cssVar: `--${trail.join('-')}`, added: !!(node.$extensions && node.$extensions.koru && node.$extensions.koru.added) });
      return;
    }
    for (const [k, v] of Object.entries(node)) if (!k.startsWith('$')) walk(v, [...trail, k], type);
  };
  walk(tokens || {}, [], undefined);
  return out;
}

function resolve(tokens, ref) {
  const t = flatten(tokens).find((x) => x.path === ref);
  if (!t) return null;
  const m = String(t.value).match(/^\{(.+)\}$/);
  return m ? resolve(tokens, m[1]) : t.value;
}

function cssValue(tokens, t) {
  const m = String(t.value).match(/^\{(.+)\}$/);
  if (m) return `var(--${m[1].replace(/\./g, '-')})`;
  return String(t.value);
}

function buildCss(tokens) {
  const lines = flatten(tokens).map((t) => `  ${t.cssVar}: ${cssValue(tokens, t)};`);
  return `/* Generated by koru ds build from tokens.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
}

// A Tailwind preset that replaces Tailwind's own palette and spacing with the tokens, so class names
// like bg-brand-500 or p-4 can only mean a token.
function buildPreset(tokens) {
  const all = flatten(tokens);
  const group = (prefix) => {
    const o = {};
    for (const t of all.filter((x) => x.path.startsWith(prefix + '.'))) {
      const keys = t.path.slice(prefix.length + 1).split('.');
      let cur = o;
      keys.slice(0, -1).forEach((k) => { cur = cur[k] = typeof cur[k] === 'object' ? cur[k] : {}; });
      cur[keys[keys.length - 1]] = `var(${t.cssVar})`;
    }
    return o;
  };
  const theme = {
    colors: { transparent: 'transparent', current: 'currentColor', ...group('color') },
    spacing: { px: '1px', ...group('space') },
    fontSize: group('font.size'),
    fontWeight: group('font.weight'),
    lineHeight: group('font.line'),
    fontFamily: Object.fromEntries(Object.entries(group('font.family')).map(([k, v]) => [k === 'base' ? 'sans' : k, [v]])),
    borderRadius: { none: '0', ...group('radius') },
    boxShadow: { none: 'none', ...group('shadow') },
  };
  return `// Generated by koru ds build from tokens.json. Do not edit.\n// Replaces Tailwind's palette, spacing and type scale: only tokens exist.\nmodule.exports = { theme: ${JSON.stringify(theme, null, 2)} };\n`;
}

// Read CSS custom properties from a client's stylesheet into DTCG tokens (no code is executed).
function importCss(text) {
  const tokens = {};
  for (const m of String(text).matchAll(/--([a-zA-Z0-9-]+)\s*:\s*([^;]+);/g)) {
    const name = m[1];
    const value = m[2].trim();
    const isColour = /^#|^rgb|^hsl/i.test(value);
    const parts = name.split('-');
    const trail = isColour ? ['color', ...groupName(parts)] : guessGroup(parts);
    let cur = tokens;
    trail.slice(0, -1).forEach((k) => { cur = cur[k] = cur[k] || {}; });
    cur[trail[trail.length - 1]] = { $type: isColour ? 'color' : /px|rem$/.test(value) ? 'dimension' : 'string', $value: value };
  }
  return tokens;
}
function groupName(parts) { return /^\d+$/.test(parts[parts.length - 1]) ? [parts.slice(0, -1).join('-'), parts[parts.length - 1]] : [parts.join('-')]; }
function guessGroup(parts) { return [parts[0], parts.slice(1).join('-') || 'default']; }

// ---------------------------------------------------------------- contrast

function luminance(hex) {
  let h = String(hex).replace('#', '');
  if (h.length === 3) h = h.split('').map((c) => c + c).join('');
  if (!/^[0-9a-f]{6}/i.test(h)) return null;
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
function mix(a, b, t) {
  const p = (h) => [0, 2, 4].map((i) => parseInt(String(h).replace('#', '').slice(i, i + 2), 16));
  const [x, y] = [p(a), p(b)];
  return '#' + x.map((v, i) => Math.round(v + (y[i] - v) * t).toString(16).padStart(2, '0')).join('').toUpperCase();
}
function ratio(a, b) {
  const la = luminance(a);
  const lb = luminance(b);
  if (la === null || lb === null) return null;
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}

function contrastReport(tokens, manifest) {
  const pairs = [];
  const ext = (tokens && tokens.$extensions && tokens.$extensions.koru && tokens.$extensions.koru.pairs) || [];
  for (const [fg, bg, use] of ext) pairs.push({ fg, bg, use: use || '' });
  for (const c of (manifest && manifest.components) || []) for (const [fg, bg, use] of c.contrast || []) pairs.push({ fg, bg, use: `${c.name}${use ? ': ' + use : ''}` });
  return pairs.map((p) => {
    const fv = /^#/.test(p.fg) ? p.fg : resolve(tokens, p.fg);
    const bv = /^#/.test(p.bg) ? p.bg : resolve(tokens, p.bg);
    const r = ratio(fv, bv);
    return { ...p, ratio: r ? Math.round(r * 100) / 100 : null, ok: r !== null && r >= 4.5, large: r !== null && r >= 3 };
  });
}

// ---------------------------------------------------------------- adopt, extend, build

function profileText(f, root) {
  let body = `# Design system\n\nThe profile every Koru skill and hook reads. Tokens live in design-system/tokens.json, components in design-system/components.json. Change them with koru ds, then koru ds build.\n\n## Audit\n\n<!-- Coverage, quality, Figma-to-code sync, governance, gaps. -->\n`;
  let old = {};
  if (root && fs.existsSync(dsPaths(root).profile)) {
    const prev = K.splitCard(fs.readFileSync(dsPaths(root).profile, 'utf8'));
    old = prev.meta || {};
    if (String(prev.body || '').trim().length > 40) body = prev.body.replace(/^\n+/, '');
  }
  const merged = { ...old, ...f };
  const head = Object.entries(merged).map(([k, v]) => `${k}: ${v === undefined ? '' : v}`).join('\n');
  return `---\n${head}\n---\n${body}`;
}

function seedComponents(id) {
  const sys = CATALOG.systems[id];
  return sys.components.map((name) => ({ name, status: 'exists', source: sys.name }));
}

function adopt(root, id, opt = {}) {
  const sys = CATALOG.systems[id];
  if (!sys) throw new Error(`Unknown system "${id}". One of: ${Object.keys(CATALOG.systems).join(', ')}`);
  const p = dsPaths(root);
  fs.mkdirSync(p.dir, { recursive: true });
  const pinned = JSON.stringify([sys.prototype, (sys.frontend || {}).packages]).match(/@(\d+\.\d+\.\d+)/);
  const version = sys.version || (id === 'koru-neutral' ? '1.0.0' : pinned ? pinned[1] : 'unversioned (code copied into the project)');
  writeFile(p.profile, profileText({
    system: sys.name, catalog_id: id, source: id === 'koru-neutral' ? 'koru-seed' : 'open-source', version,
    licence: sys.licence, stack: opt.stack || sys.stack.join(' | '), prototype_mode: sys.prototype.mode, restrictions: JSON.stringify(sys.restrictions || ''),
  }, root));
  const tokens = id === 'koru-neutral' ? readJson(path.join(SEED_DIR, 'koru-neutral.tokens.json'), {}) : { $description: `${sys.name} tokens come from its own package (${(sys.frontend || {}).tokens || ''}). Add only brand overrides here.` };
  writeFile(p.tokens, JSON.stringify(tokens, null, 2) + '\n');
  const manifest = {
    system: sys.name, catalog_id: id, version, source: id === 'koru-neutral' ? 'koru-seed' : 'open-source',
    tailwind: id === 'koru-neutral' || id === 'shadcn',
    match: sys.match, prototype: sys.prototype, frontend: sys.frontend || {},
    uiLayer: (opt.uiLayer || 'src/ui'),
    components: seedComponents(id),
  };
  writeFile(p.manifest, JSON.stringify(manifest, null, 2) + '\n');
  build(root);
  return { sys, version };
}

// Extend a client's own system: import its colour tokens, keep its components, map Koru's semantic
// roles (accent, ink, danger…) onto the client's names, and add what it lacks (spacing, type, missing
// colours) as clearly marked additions to contribute back. Nothing the client has is overwritten.
const ROLE_GROUPS = { accent: ['accent', 'brand', 'primary'], ink: ['ink', 'neutral', 'gray', 'grey', 'slate'], danger: ['danger', 'error', 'red'], warning: ['warning', 'amber', 'yellow'], success: ['success', 'green'], ai: ['ai'] };

function extend(root, opt) {
  const p = dsPaths(root);
  fs.mkdirSync(p.dir, { recursive: true });
  const css = opt.css ? fs.readFileSync(path.resolve(opt.css), 'utf8') : '';
  const tokens = importCss(css);
  const seed = readJson(path.join(SEED_DIR, 'koru-neutral.tokens.json'), {});
  const clone = (x) => JSON.parse(JSON.stringify(x));
  const added = (v, why) => ({ $type: 'color', $value: v, $extensions: { koru: { added: true, why } } });
  const mark = (node) => { if (node && typeof node === 'object') { if ('$value' in node) node.$extensions = { koru: { added: true } }; else Object.values(node).forEach(mark); } return node; };
  for (const g of ['space', 'font', 'radius', 'size', 'shadow']) if (!tokens[g]) tokens[g] = mark(clone(seed[g]));
  tokens.color = tokens.color || {};
  const clientColour = tokens.color;
  const roles = [];
  // Semantic roles. A role the client has under its own name becomes an alias; a missing shade
  // takes the seed value and is marked as an addition.
  for (const [role, names] of Object.entries(ROLE_GROUPS)) {
    const seedGroup = seed.color[role];
    const own = names.find((n) => clientColour[n] && typeof clientColour[n] === 'object');
    for (const shade of Object.keys(seedGroup)) {
      if (own && clientColour[own][shade]) {
        if (own !== role) { tokens.color[role] = tokens.color[role] || {}; tokens.color[role][shade] = { $type: 'color', $value: `{color.${own}.${shade}}` }; roles.push(`${role}.${shade} → ${own}.${shade}`); }
      } else {
        const target = own || role;
        tokens.color[target] = tokens.color[target] || {};
        if (!tokens.color[target][shade]) tokens.color[target][shade] = added(seedGroup[shade].$value, own ? `${own} has no ${shade} shade` : `the client has no ${role} colours`);
        if (own && own !== role) { tokens.color[role] = tokens.color[role] || {}; tokens.color[role][shade] = { $type: 'color', $value: `{color.${own}.${shade}}` }; }
        roles.push(`${role}.${shade} added`);
      }
    }
  }
  for (const k of ['surface', 'canvas', 'on-accent']) if (!tokens.color[k]) tokens.color[k] = added(seed.color[k].$value, 'semantic role the client does not name');
  // An added canvas must keep the client's helper text readable: lighten it until it does.
  if (tokens.color.canvas.$extensions && tokens.color.canvas.$extensions.koru.added) {
    const ink = resolve(tokens, 'color.ink.500');
    let c = tokens.color.canvas.$value;
    for (let i = 0; i < 6 && ink && ratio(ink, c) < 4.5; i++) c = mix(c, '#FFFFFF', 0.35);
    if (ink && ratio(ink, c) < 4.5) c = resolve(tokens, 'color.surface') || '#FFFFFF';
    if (c !== tokens.color.canvas.$value) tokens.color.canvas = added(c, 'changed so the client\'s ink.500 helper text keeps 4.5:1 (no tinted canvas reaches it)');
  }
  if (!tokens.color.focus) tokens.color.focus = { $type: 'color', $value: '{color.accent.600}', $extensions: { koru: { added: true } } };
  // Contrast pairs: Koru's semantic pairs, plus every text-on-background pair the client's own
  // component markup uses (so a documented failure such as white on brand-500 is caught).
  const pairs = clone(seed.$extensions.koru.pairs);
  if (opt.componentsDoc) {
    const doc = fs.readFileSync(path.resolve(opt.componentsDoc), 'utf8');
    for (const m of doc.matchAll(/class="([^"]+)"/g)) {
      const cls = m[1].split(/\s+/);
      const bg = cls.map((c) => c.match(/^bg-([a-z]+(?:-\d{2,3})?)$/)).find(Boolean);
      const fg = cls.map((c) => c.match(/^text-([a-z]+(?:-\d{2,3})?)$/)).find((x) => x && !/^(xs|sm|base|md|lg|xl|\d?xl|left|right|center)$/.test(x[1]));
      if (bg && fg) {
        const ref = (n) => (n === 'white' ? '#FFFFFF' : n === 'black' ? '#000000' : `color.${n.replace('-', '.')}`);
        const use = `client markup: ${fg[0]} on ${bg[0]}`;
        if (!pairs.some((x) => x[2] === use)) pairs.push([ref(fg[1]), ref(bg[1]), use]);
      }
    }
  }
  tokens.$extensions = { koru: { pairs, roles } };
  writeFile(p.tokens, JSON.stringify(tokens, null, 2) + '\n');
  const exists = String(opt.components || '').split(',').map((s) => s.trim()).filter(Boolean);
  const manifest = {
    system: opt.name || 'Client system', version: opt.version || 'unknown', source: 'client', tailwind: !!opt.tailwind,
    match: { data: true }, prototype: { mode: 'inline' }, frontend: { imports: [opt.uiLayer || 'src/ui'] }, uiLayer: opt.uiLayer || 'src/ui',
    components: exists.map((name) => ({ name, status: 'exists', source: opt.name || 'client' })),
  };
  writeFile(p.manifest, JSON.stringify(manifest, null, 2) + '\n');
  writeFile(p.profile, profileText({ system: manifest.system, source: 'client', version: manifest.version, licence: 'client-owned', stack: opt.stack || (opt.tailwind ? 'tailwind' : 'html'), prototype_mode: 'inline' }, root));
  build(root);
  const flat = flatten(tokens);
  return { tokens: flat.length, added: flat.filter((t) => t.added).length, components: exists.length, roles };
}

// ---------------------------------------------------------------- components and governance

function addComponent(root, name, opt = {}) {
  const p = dsPaths(root);
  const man = readJson(p.manifest, null);
  if (!man) throw new Error('No design system yet. Run koru ds adopt or koru ds extend first.');
  if (man.components.some((c) => c.name.toLowerCase() === name.toLowerCase())) throw new Error(`${name} is already in the manifest.`);
  const status = opt.status || 'new';
  if (!['new', 'snowflake', 'exists'].includes(status)) throw new Error('--status is new (a gap the system should gain), snowflake (a one-off this project needs, with a Decision) or exists.');
  if (status === 'snowflake' && !/^DEC-\d{3}$/.test(String(opt.spec || ''))) throw new Error('A snowflake is a one-off outside the system. It needs the Decision that allows it: --spec DEC-004.');
  if (status === 'new' && !/^(SCR|DIR|DEC|STA)-\d{3}$/.test(String(opt.spec || ''))) throw new Error(`A new component needs the card that asks for it: --spec SCR-001 (or DIR, DEC, STA). It is a gap to contribute back to ${man.system}, so it needs a reason on record.`);
  const c = { name, status, source: status === 'exists' ? man.system : `koru-${status}`, spec: opt.spec || '', states: String(opt.states || 'default,hover,focus,disabled').split(',').map((x) => x.trim()) };
  if (opt.contrast) c.contrast = [].concat(opt.contrast).map((x) => String(x).split(',').map((y) => y.trim()));
  man.components.push(c);
  writeFile(p.manifest, JSON.stringify(man, null, 2) + '\n');
  build(root);
  return c;
}

const fingerprint = (root) => {
  const p = dsPaths(root);
  return require('crypto').createHash('sha256').update([p.tokens, p.manifest].map((f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '')).join('\n')).digest('hex').slice(0, 16);
};
function approval(root) {
  const f = K.stateFile(root, 'ds-approvals.jsonl');
  const last = K.readJsonl(f).pop();
  if (!last) return { approved: false, current: false };
  return { ...last, approved: true, current: last.hash === fingerprint(root) };
}
function approve(root, name, role) {
  const rep = check(root);
  if (rep.blocks.length) throw new Error(`Fix these first:\n- ${rep.blocks.join('\n- ')}`);
  const rec = { at: K.now(), by: name, role: role || '', hash: fingerprint(root), system: rep.system, version: rep.version };
  K.appendJsonl(K.stateFile(root, 'ds-approvals.jsonl'), rec);
  return rec;
}

// Health of the system itself: contrast, governance of additions, build freshness.
function check(root) {
  const ds = load(root);
  const blocks = [];
  const warns = [];
  if (!ds.ready) return { blocks: ['No design system. Run koru ds adopt <id> or koru ds extend.'], warns, contrast: [] };
  const contrast = ds.tokens ? contrastReport(ds.tokens, ds.manifest) : [];
  const suggest = (c) => {
    const m = String(c.bg).match(/^color\.([a-z-]+)\.(\d+)$/);
    if (!m) return '';
    const fv = /^#/.test(c.fg) ? c.fg : resolve(ds.tokens, c.fg);
    const shades = flatten(ds.tokens).filter((t) => t.path.startsWith(`color.${m[1]}.`) && Number(t.path.split('.').pop()) > Number(m[2]));
    const ok = shades.map((t) => ({ t, r: ratio(fv, resolve(ds.tokens, t.path)) })).filter((x) => x.r >= 4.5)[0];
    return ok ? ` ${ok.t.path} passes (${Math.round(ok.r * 100) / 100}:1).` : '';
  };
  for (const c of contrast.filter((x) => !x.ok && /^client markup/.test(x.use))) warns.push(`${ds.manifest.system}'s own markup fails AA: ${c.use.replace('client markup: ', '')} is ${c.ratio}:1.${suggest(c)} Deliverables cannot use it (the lint refuses it); report it back to the client's system owner.`);
  for (const c of contrast.filter((x) => !x.ok && !/^client markup/.test(x.use))) blocks.push(`Contrast ${c.ratio === null ? '?' : c.ratio + ':1'} for ${c.use} (${c.fg} on ${c.bg}); AA needs 4.5:1 for text${c.large ? '. It passes only for large text (18px+, or 14px bold)' : ''}.${suggest(c)}`);
  const cards = fs.existsSync(K.paths(root).cards) ? K.loadCards(root) : {};
  for (const c of ds.manifest.components.filter((x) => ['new', 'snowflake'].includes(x.status))) {
    if (!c.spec) blocks.push(`${c.name} is ${c.status} but names no card.`);
    else if (!cards[c.spec]) blocks.push(`${c.name} cites ${c.spec}, which does not exist.`);
    else if (c.status === 'snowflake' && cards[c.spec].status !== 'final') blocks.push(`${c.name} is a snowflake, but ${c.spec} is not signed yet.`);
  }
  const built = fs.existsSync(ds.paths.css) ? fs.readFileSync(ds.paths.css, 'utf8') : '';
  if (built !== buildCss(ds.tokens || {})) warns.push('build/ is older than tokens.json. Run koru ds build.');
  const additions = flatten(ds.tokens || {}).filter((t) => t.added);
  const newComps = ds.manifest.components.filter((x) => x.status === 'new');
  return { system: ds.manifest.system, version: ds.manifest.version, blocks, warns, contrast, additions: additions.length, newComponents: newComps.map((c) => c.name), approval: approval(root) };
}

function build(root) {
  const { paths: p, tokens, manifest } = load(root);
  fs.mkdirSync(p.build, { recursive: true });
  writeFile(p.css, buildCss(tokens || {}));
  writeFile(p.preset, buildPreset(tokens || {}));
  const kitSrc = path.join(SEED_DIR, 'koru-neutral.css');
  if (manifest && (manifest.catalog_id === 'koru-neutral' || manifest.source === 'client')) writeFile(p.kit, fs.readFileSync(kitSrc, 'utf8'));
  writeFile(p.gallery, gallery(root));
  return p;
}

// The block a standalone prototype inlines: tokens plus the component kit. The lint checks it is
// exactly this, so nobody adds a colour inside it by hand.
function inlineBlock(root) {
  const p = dsPaths(root);
  const parts = [fs.existsSync(p.css) ? fs.readFileSync(p.css, 'utf8') : '', fs.existsSync(p.kit) ? fs.readFileSync(p.kit, 'utf8') : ''];
  return parts.join('\n').trim();
}
function headLinks(root) {
  const { manifest } = load(root);
  const pr = (manifest && manifest.prototype) || {};
  const out = [];
  for (const c of pr.css || []) if (/^https:/.test(c)) out.push(`<link rel="stylesheet" href="${c}">`);
  for (const j of pr.js || []) out.push(`<script src="${j}" defer></script>`);
  for (const j of pr.js_module || []) out.push(`<script type="module" src="${j}"></script>`);
  return out;
}
function inlineInto(root, html) {
  const block = `<style data-koru-tokens>\n${inlineBlock(root)}\n</style>`;
  const links = headLinks(root).filter((l) => !html.includes(l)).join('\n');
  if (/<style data-koru-tokens>[\s\S]*?<\/style>/.test(html)) return html.replace(/<style data-koru-tokens>[\s\S]*?<\/style>/, block);
  return html.replace(/<\/head>/i, `${links ? links + '\n' : ''}${block}\n</head>`);
}

function gallery(root) {
  const { manifest, tokens } = load(root);
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;');
  const sw = flatten(tokens || {}).filter((t) => t.type === 'color' && !/^\{/.test(String(t.value)));
  const rows = ((manifest && manifest.components) || []).map((c) => `<tr><td>${esc(c.name)}</td><td>${esc(c.status)}</td><td>${esc(c.spec || '')}</td><td>${esc(c.source || '')}</td></tr>`).join('');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc((manifest && manifest.system) || 'Design system')} · Koru gallery</title>
<style>body{font:14px/1.5 system-ui,sans-serif;margin:24px;color:#1b2230}table{border-collapse:collapse}td,th{border-bottom:1px solid #e7eaef;padding:6px 10px;text-align:left}.sw{display:inline-flex;flex-direction:column;width:120px;margin:0 8px 8px 0;font-size:12px}.sw i{height:40px;border-radius:6px;border:1px solid #e7eaef}</style></head><body>
<h1>${esc((manifest && manifest.system) || 'Design system')} ${esc((manifest && manifest.version) || '')}</h1>
<h2>Colour tokens</h2><div>${sw.map((t) => `<span class="sw"><i style="background:${esc(t.value)}"></i>${esc(t.path)}<br>${esc(t.value)}${t.added ? ' · added' : ''}</span>`).join('')}</div>
<h2>Components</h2><table><tr><th>Component</th><th>Status</th><th>Spec</th><th>Source</th></tr>${rows}</table></body></html>`;
}

